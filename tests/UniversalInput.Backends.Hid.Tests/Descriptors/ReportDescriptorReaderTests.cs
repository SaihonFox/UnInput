using UniversalInput.Backends.Hid.Descriptors;

namespace UniversalInput.Backends.Hid.Tests.Descriptors;

public class ReportDescriptorReaderTests
{
	private static readonly byte[] BootKeyboard =
	[
		0x05, 0x01, 0x09, 0x06, 0xA1, 0x01, 0x05, 0x07, 0x19, 0xE0, 0x29, 0xE7, 0x15, 0x00, 0x25, 0x01,
		0x75, 0x01, 0x95, 0x08, 0x81, 0x02, 0x95, 0x01, 0x75, 0x08, 0x81, 0x01, 0x95, 0x05, 0x75, 0x01,
		0x05, 0x08, 0x19, 0x01, 0x29, 0x05, 0x91, 0x02, 0x95, 0x01, 0x75, 0x03, 0x91, 0x01, 0x95, 0x06,
		0x75, 0x08, 0x15, 0x00, 0x25, 0x65, 0x05, 0x07, 0x19, 0x00, 0x29, 0x65, 0x81, 0x00, 0xC0,
	];

	private static readonly byte[] Mouse =
	[
		0x05, 0x01, 0x09, 0x02, 0xA1, 0x01, 0x09, 0x01, 0xA1, 0x00, 0x05, 0x09, 0x19, 0x01, 0x29, 0x03,
		0x15, 0x00, 0x25, 0x01, 0x95, 0x03, 0x75, 0x01, 0x81, 0x02, 0x95, 0x01, 0x75, 0x05, 0x81, 0x01,
		0x05, 0x01, 0x09, 0x30, 0x09, 0x31, 0x15, 0x81, 0x25, 0x7F, 0x75, 0x08, 0x95, 0x02, 0x81, 0x06,
		0xC0, 0xC0,
	];

	[Fact]
	public void BootKeyboard_IsOneKeyboardCollection()
	{
		Assert.Equal<HidUsage>([new HidUsage(0x01, 0x06)], ReportDescriptorReader.ReadApplicationUsages(BootKeyboard));
	}

	[Fact]
	public void Mouse_NestedPointerCollection_IsNotCountedSeparately()
	{
		Assert.Equal<HidUsage>([new HidUsage(0x01, 0x02)], ReportDescriptorReader.ReadApplicationUsages(Mouse));
	}

	[Fact]
	public void Gamepad_IsRecognized()
	{
		byte[] gamepad = [0x05, 0x01, 0x09, 0x05, 0xA1, 0x01, 0x05, 0x09, 0x19, 0x01, 0x29, 0x08, 0x15, 0x00, 0x25, 0x01, 0x75, 0x01, 0x95, 0x08, 0x81, 0x02, 0xC0];

		Assert.Equal<HidUsage>([new HidUsage(0x01, 0x05)], ReportDescriptorReader.ReadApplicationUsages(gamepad));
	}

	[Fact]
	public void SeveralTopLevelCollections_AreReportedInOrder()
	{
		byte[] composite = [0x05, 0x01, 0x09, 0x06, 0xA1, 0x01, 0x85, 0x01, 0xC0, 0x05, 0x01, 0x09, 0x02, 0xA1, 0x01, 0x85, 0x02, 0xC0];

		Assert.Equal<HidUsage>([new HidUsage(0x01, 0x06), new HidUsage(0x01, 0x02)], ReportDescriptorReader.ReadApplicationUsages(composite));
	}

	[Fact]
	public void VendorPage_WithTwoByteValue_IsRead()
	{
		byte[] vendor = [0x06, 0x00, 0xFF, 0x09, 0x01, 0xA1, 0x01, 0xC0];

		Assert.Equal<HidUsage>([new HidUsage(0xFF00, 0x01)], ReportDescriptorReader.ReadApplicationUsages(vendor));
	}

	[Fact]
	public void ExtendedUsage_CarriesItsOwnPage()
	{
		// Страница 0xFF00 задана отдельно, но четырёхбайтовое применение 0x0001:0x0006 её перекрывает.
		byte[] extended = [0x06, 0x00, 0xFF, 0x0B, 0x06, 0x00, 0x01, 0x00, 0xA1, 0x01, 0xC0];

		Assert.Equal<HidUsage>([new HidUsage(0x01, 0x06)], ReportDescriptorReader.ReadApplicationUsages(extended));
	}

	[Fact]
	public void PushAndPop_RestoreTheUsagePage()
	{
		byte[] pushed = [0x05, 0x01, 0xA4, 0x05, 0x0D, 0xB4, 0x09, 0x06, 0xA1, 0x01, 0xC0];

		Assert.Equal<HidUsage>([new HidUsage(0x01, 0x06)], ReportDescriptorReader.ReadApplicationUsages(pushed));
	}

	[Fact]
	public void LongItems_AreSkipped()
	{
		byte[] withLongItem = [0xFE, 0x02, 0x10, 0xAA, 0xBB, 0x05, 0x01, 0x09, 0x06, 0xA1, 0x01, 0xC0];

		Assert.Equal<HidUsage>([new HidUsage(0x01, 0x06)], ReportDescriptorReader.ReadApplicationUsages(withLongItem));
	}

	[Fact]
	public void NonApplicationTopLevelCollection_IsIgnored()
	{
		byte[] physical = [0x05, 0x01, 0x09, 0x02, 0xA1, 0x00, 0xC0];

		Assert.Empty(ReportDescriptorReader.ReadApplicationUsages(physical));
	}

	[Fact]
	public void BrokenInput_DoesNotThrow()
	{
		Assert.Empty(ReportDescriptorReader.ReadApplicationUsages([]));
		Assert.Empty(ReportDescriptorReader.ReadApplicationUsages([0x05, 0x01, 0x09, 0x06, 0xA1]));
		Assert.Empty(ReportDescriptorReader.ReadApplicationUsages([0xFE]));
		Assert.Empty(ReportDescriptorReader.ReadApplicationUsages([0xFE, 0xFF, 0x10]));
	}

	[Fact]
	public void UsageWithoutACollection_IsNotReported()
	{
		byte[] noCollection = [0x05, 0x01, 0x09, 0x06];

		Assert.Empty(ReportDescriptorReader.ReadApplicationUsages(noCollection));
	}

	[Fact]
	public void ToString_FormatsPageAndUsageInHex()
	{
		Assert.Equal("FF00:0001", new HidUsage(0xFF00, 1).ToString());
	}
}
